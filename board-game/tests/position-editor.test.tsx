// @vitest-environment jsdom
import { act, renderHook } from '@testing-library/react'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { usePositionEditor } from '../src/features/game/hooks/usePositionEditor'
import { useSessionStore } from '../src/store/sessionStore'
import { useGameStore } from '../src/store/gameStore'
import { pikafishApi } from '../src/services/pikafish'
import { fireEvent, render, screen } from '@testing-library/react'
import { PositionPalette } from '../src/features/game/components/PositionPalette'
import { createInitialBoard } from '../src/game/state/initial'
import { emptyPosition } from '../src/game/state/customPosition'
vi.mock('../src/services/pikafish', () => ({ pikafishApi: { ready: vi.fn().mockResolvedValue(undefined) } }))

beforeEach(() => {
  vi.clearAllMocks()
  useGameStore.getState().reset(0)
  useSessionStore.setState({ screen: 'position', humanSide: 'red', computerLevel: 6 })
})
describe('Trình chỉnh thế cờ', () => {
  it('bên đi tiên độc lập với bên người chơi cầm', async () => {
    const { result } = renderHook(usePositionEditor)
    expect(result.current.firstSide).toBe('red')
    act(() => result.current.changeSide('black'))
    act(() => result.current.setFirstSide('red'))
    await act(() => result.current.start())
    expect(useGameStore.getState().game.currentTurn).toBe('red')
    expect(useSessionStore.getState().humanSide).toBe('black')
  })
  it('tự ẩn thông báo sau 3 giây', () => {
    vi.useFakeTimers()
    const { result, unmount } = renderHook(usePositionEditor)
    act(() => result.current.setNotice('Tốt đang ở vị trí không thể đi tới.'))
    expect(result.current.notice).toBe('Tốt đang ở vị trí không thể đi tới.')
    act(() => vi.advanceTimersByTime(2999))
    expect(result.current.notice).not.toBe('')
    act(() => vi.advanceTimersByTime(1))
    expect(result.current.notice).toBe('')
    unmount()
    vi.useRealTimers()
  })
  it('phím mũi tên chọn khay màu, phím số và click số chọn đúng quân', () => {
    const choose = vi.fn()
    const view = render(<PositionPalette board={emptyPosition()} piece={null} onChoose={choose} onReset={() => {}} onDelete={() => {}} />)
    fireEvent.keyDown(window, { key: 'ArrowDown' })
    fireEvent.keyDown(window, { key: '1' })
    expect(choose).toHaveBeenLastCalledWith('red', 'rook')
    fireEvent.keyDown(window, { key: 'ArrowUp' })
    fireEvent.keyDown(window, { key: 'w' })
    expect(choose).toHaveBeenLastCalledWith('black', 'soldier')
    fireEvent.click(view.getByRole('group', { name: 'Quân Đỏ' }))
    fireEvent.keyDown(window, { key: 'q' })
    expect(choose).toHaveBeenLastCalledWith('red', 'cannon')
    fireEvent.click(view.getByRole('button', { name: 'Đặt Mã đỏ' }).querySelector('span')!)
    expect(choose).toHaveBeenLastCalledWith('red', 'horse')
    view.rerender(<PositionPalette board={emptyPosition()} piece={{ side: 'black', type: 'cannon' }} onChoose={choose} onReset={() => {}} onDelete={() => {}} />)
    expect(view.getByRole('group', { name: 'Quân Đen' }).className).toContain('outline-2')
    expect(view.getByRole('group', { name: 'Quân Đỏ' }).className).not.toContain('outline-2')
    expect(view.getByRole('button', { name: 'Đặt Pháo đen' }).getAttribute('aria-pressed')).toBe('true')
    view.unmount()
  })
  it('xóa giữ hai Tướng, cho xếp thế đối mặt nhưng chặn Đấu ngay', async () => {
    const { result } = renderHook(usePositionEditor)
    act(() => result.current.clearPieces())
    expect(result.current.board.flat().filter(Boolean)).toHaveLength(2)
    act(() => result.current.drop({ side: 'red', type: 'rook' }, { row: 5, col: 0 }))
    expect(result.current.board[5][0]?.type).toBe('rook')
    expect(result.current.notice).toBe('')
    await act(() => result.current.start())
    expect(result.current.notice).toContain('đối mặt')
    expect(pikafishApi.ready).not.toHaveBeenCalled()
    expect(useSessionStore.getState().screen).toBe('position')
  })
  it('đặt rồi chuyển quân bằng click; xóa hết trừ Tướng và cài lại đủ32 quân', () => {
    const { result } = renderHook(usePositionEditor)
    act(() => result.current.remove({ row: 9, col: 0 }))
    act(() => result.current.choose('red', 'rook'))
    act(() => result.current.select({ row: 4, col: 0 }))
    expect(result.current.board[4][0]?.type).toBe('rook')
    act(() => result.current.select({ row: 4, col: 0 }))
    act(() => result.current.select({ row: 4, col: 1 }))
    expect(result.current.board[4][0]).toBeNull()
    expect(result.current.board[4][1]?.type).toBe('rook')
    act(() => result.current.clearPieces())
    act(() => result.current.select({ row: 4, col: 1 }))
    expect(result.current.board[4][1]).toBeNull()
    act(() => result.current.reset())
    expect(result.current.board.flat().filter(Boolean)).toHaveLength(32)
  })
  it('chuột phải lấy quân khỏi bàn và tự chọn đúng bên cùng loại quân', () => {
    const { result } = renderHook(usePositionEditor)
    act(() => result.current.removeAndChoose({ row: 9, col: 0 }))
    expect(result.current.board[9][0]).toBeNull()
    expect(result.current.piece).toEqual({ side: 'red', type: 'rook' })
  })
  it('không chạy máy khi thế thiếu Tướng', async () => {
    const { result } = renderHook(usePositionEditor)
    act(() => result.current.remove({ row: 0, col: 4 }))
    await act(() => result.current.start())
    expect(result.current.notice).toContain('Tướng')
    expect(pikafishApi.ready).not.toHaveBeenCalled()
    expect(useSessionStore.getState().screen).toBe('position')
  })
  it('chặn đặt sai ô và làm mờ quân đã đạt giới hạn', () => {
    const { result } = renderHook(usePositionEditor)
    act(() => result.current.remove({ row: 9, col: 4 }))
    act(() => result.current.choose('red', 'general'))
    act(() => result.current.select({ row: 9, col: 0 }))
    expect(result.current.board[9][0]?.type).toBe('rook')
    expect(result.current.notice).toContain('trong cung')
    expect(result.current.piece).toEqual({ side: 'red', type: 'general' })
    render(<PositionPalette board={createInitialBoard()} piece={null} onChoose={() => {}} onReset={() => {}} onDelete={() => {}} />)
    expect(screen.getByRole('button', { name: 'Đặt Tướng đỏ, đã hết quân' })).toHaveProperty('disabled', true)
    expect(screen.getByRole('button', { name: 'Đặt Tướng đen, đã hết quân' })).toHaveProperty('disabled', true)
  })
  it('Đấu ngay giữ cấp đã chọn và đưa đúng FEN/bên Đen đi trước vào game', async () => {
    const { result } = renderHook(usePositionEditor)
    act(() => result.current.changeSide('black'))
    act(() => result.current.setFirstSide('black'))
    await act(() => result.current.start())
    expect(useGameStore.getState().initialFen).toContain(' b - - 0 1')
    expect(useGameStore.getState().game.currentTurn).toBe('black')
    expect(useSessionStore.getState()).toMatchObject({ screen: 'game', mode: 'computer', humanSide: 'black', computerEngine: 'pikafish', computerLevel: 6 })
  })
  it('kéo trực tiếp quân trên bàn, thả ngoài để xóa, kéo từ khay vẫn kiểm tra luật', () => {
    const { result } = renderHook(usePositionEditor)
    act(() => result.current.drop({ side: 'red', type: 'rook', from: { row: 9, col: 0 } }, { row: 5, col: 0 }))
    expect(result.current.board[9][0]).toBeNull()
    expect(result.current.board[5][0]?.type).toBe('rook')
    act(() => result.current.drop({ side: 'red', type: 'rook', from: { row: 5, col: 0 } }, null))
    expect(result.current.board[5][0]).toBeNull()
    expect(result.current.piece).toEqual({ side: 'red', type: 'rook' })
    act(() => result.current.drop({ side: 'red', type: 'rook' }, { row: 4, col: 0 }))
    expect(result.current.board[4][0]?.type).toBe('rook')
    act(() => result.current.drop({ side: 'red', type: 'general', from: { row: 9, col: 4 } }, { row: 4, col: 4 }))
    expect(result.current.board[9][4]?.type).toBe('general')
    expect(result.current.board[4][4]).toBeNull()
    expect(result.current.selected).toBeNull()
    expect(result.current.notice).toContain('trong cung')
  })
  it('kéo từ khay chọn đúng màu/quân và giữ chọn đến khi hết loại quân đó', () => {
    const { result } = renderHook(usePositionEditor)
    act(() => result.current.clearPieces())
    act(() => result.current.choose('red', 'soldier'))
    act(() => result.current.chooseForDrag('black', 'cannon'))
    expect(result.current.piece).toEqual({ side: 'black', type: 'cannon' })
    act(() => result.current.drop({ side: 'black', type: 'cannon' }, { row: 2, col: 1 }))
    expect(result.current.piece).toEqual({ side: 'black', type: 'cannon' })
    act(() => result.current.chooseForDrag('black', 'cannon'))
    expect(result.current.piece).toEqual({ side: 'black', type: 'cannon' })
    act(() => result.current.drop({ side: 'black', type: 'cannon' }, { row: 2, col: 7 }))
    expect(result.current.piece).toBeNull()
  })
})
