import { beforeEach, expect, it } from 'vitest'
import { RoomRepository } from '../server/repositories/roomRepository'
import { RoomService } from '../server/services/roomService'

let now: number, service: RoomService, id: string
beforeEach(() => {
  now = 0
  service = new RoomService(new RoomRepository(), () => now, () => 'red')
  id = service.create('Bàn').id
  service.join(id, 'a', 'Người A')
  service.join(id, 'b', 'Người B')
})
const queue = () => { service.join(id, 'c', 'Người C'); return service.command('c', { type: 'join-queue' }) }
const ready = (player: string) => service.command(player, { type: 'ready' })
const tickAt = (time: number) => { now = time; return service.tick() }

it.each([false, true])('không có người chờ thì không tự bắt đầu/phạt, một người ready=%s', oneReady => {
  const room = oneReady ? ready('a') : service.roomFor('a')!
  tickAt(100_000)
  expect(room.game.phase).toBe('ready')
  expect(room.readyCountdown).toBeNull()
  expect(room.players.map(player => player.id)).toEqual(['a', 'b'])
})
it('đủ hai người chưa ready: 10s hiện20, 29s hiện1, 30s tự bắt đầu', () => {
  const room = queue()
  tickAt(9999)
  expect(room.readyCountdown).toBeNull()
  tickAt(10_000)
  expect(room.readyCountdown).toBe(20)
  tickAt(29_000)
  expect(room.readyCountdown).toBe(1)
  tickAt(30_000)
  expect(room.game.phase).toBe('playing')
  expect(room.game.lastClockUpdate).toBe(31_300)
  expect(room.readyCountdown).toBeNull()
  expect(room.players.every(player => player.ready)).toBe(true)
})
it('một người ready hủy đếm hiện, tính30s mới rồi đổi đúng ghế mà không ghi thắng/thua', () => {
  const room = queue()
  tickAt(15_000)
  expect(room.readyCountdown).toBe(15)
  ready('a')
  expect(room.readyCountdown).toBeNull()
  tickAt(44_999)
  expect(room.players.map(player => player.id)).toEqual(['a', 'b'])
  tickAt(45_000)
  expect(room.players.map(player => player.id)).toEqual(['a', 'c'])
  expect(room.players.find(player => player.id === 'a')?.ready).toBe(true)
  expect(room.viewers).toContainEqual(expect.objectContaining({ id: 'b', queued: false }))
  expect(room.lastCompletedMatch).toBeUndefined()
  expect(room.game.phase).toBe('ready')
})
it('người thứ hai ready đúng hạn thì bắt đầu, không đổi ghế', () => {
  const room = queue()
  ready('a')
  tickAt(29_999)
  ready('b')
  tickAt(31_000)
  expect(room.game.phase).toBe('playing')
  expect(room.players.map(player => player.id)).toEqual(['a', 'b'])
})
it('người chờ bỏ hàng thì hủy countdown và không phạt', () => {
  const room = queue()
  tickAt(15_000)
  service.command('c', { type: 'leave-queue' })
  expect(room.readyCountdown).toBeNull()
  tickAt(40_000)
  expect(room.game.phase).toBe('ready')
})
it('người chờ rời phòng hủy cả thời gian phạt ngầm', () => {
  const room = queue()
  ready('a')
  tickAt(20_000)
  service.leave('c')
  tickAt(60_000)
  expect(room.players.map(player => player.id)).toEqual(['a', 'b'])
  expect(room.lastCompletedMatch).toBeUndefined()
})
it('không thể bấm lại ready/reset để kéo dài thời gian chờ', () => {
  const room = queue()
  ready('a')
  tickAt(20_000)
  ready('a')
  expect(() => service.command('a', { type: 'reset' })).toThrow()
  tickAt(30_000)
  expect(room.players.map(player => player.id)).toEqual(['a', 'c'])
})
it('đổi cả ghế đỏ, giữ FIFO và cho người mới đủ30s riêng', () => {
  const room = queue()
  service.join(id, 'd', 'Người D')
  service.command('d', { type: 'join-queue' })
  ready('b')
  tickAt(30_000)
  expect(room.players.map(player => player.id)).toEqual(['c', 'b'])
  expect(room.lastCompletedMatch).toBeUndefined()
  tickAt(59_999)
  expect(room.players.map(player => player.id)).toEqual(['c', 'b'])
  tickAt(60_000)
  expect(room.players.map(player => player.id)).toEqual(['d', 'b'])
})
it('sau ván vẫn đổi người thua sau3s, cặp mới có đủ10+20s', () => {
  const room = queue()
  ready('a'); ready('b')
  service.command('a', { type: 'resign' })
  expect(room.players.every(player => !player.ready)).toBe(true)
  tickAt(3000)
  expect(room.players.map(player => player.id)).toEqual(['c', 'b'])
  tickAt(12_999)
  expect(room.readyCountdown).toBeNull()
  tickAt(13_000)
  expect(room.readyCountdown).toBe(20)
  tickAt(33_000)
  expect(room.game.phase).toBe('playing')
})
it('đổi ghế vì chưa ready giữ nguyên archive ván thật trước đó', () => {
  const room = queue()
  ready('a'); ready('b')
  service.command('a', { type: 'resign' })
  const archive = room.lastCompletedMatch
  tickAt(3000)
  ready('b')
  tickAt(33_000)
  expect(room.players.map(player => player.id)).toEqual(['a', 'b'])
  expect(room.lastCompletedMatch).toBe(archive)
  expect(room.lastCompletedMatch?.states.at(-1)?.result).toEqual({ winner: 'black', reason: 'resign' })
})
